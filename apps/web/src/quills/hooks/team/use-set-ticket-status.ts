import { useMutation, useQueryClient } from "@tanstack/react-query";
import type { PortalProblem, Viewer } from "../../core/types";
import { quillsOperationKey } from "../../api/keys";
import {
  setTicketStatus,
  type SetTicketStatusRequest,
  type SetTicketStatusResponse,
} from "../../api/team/set-ticket-status";
export function useSetTicketStatus(viewer: Viewer) {
  const queryClient = useQueryClient();
  return useMutation<
    SetTicketStatusResponse,
    PortalProblem,
    SetTicketStatusRequest
  >({
    mutationFn: (input) => setTicketStatus(input),
    onSuccess: async (_data, input) => {
      await Promise.all([
        queryClient.invalidateQueries({
          queryKey: quillsOperationKey(
            input.param.workspaceId,
            viewer,
            "team",
            "listTickets",
          ),
        }),
        queryClient.invalidateQueries({
          queryKey: quillsOperationKey(
            input.param.workspaceId,
            viewer,
            "team",
            "getTicket",
          ),
        }),
        queryClient.invalidateQueries({
          queryKey: quillsOperationKey(
            input.param.workspaceId,
            viewer,
            "team",
            "listTicketActivity",
          ),
        }),
        queryClient.invalidateQueries({
          queryKey: quillsOperationKey(
            input.param.workspaceId,
            viewer,
            "team",
            "getTeamCounts",
          ),
        }),
        queryClient.invalidateQueries({
          queryKey: quillsOperationKey(
            input.param.workspaceId,
            viewer,
            "team",
            "listTicketMessages",
          ),
        }),
      ]);
    },
  });
}
